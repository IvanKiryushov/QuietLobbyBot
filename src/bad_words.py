import re

# Мощное регулярное выражение для поиска основных корней русского мата.
# Покрывает большинство словоформ, приставок и суффиксов, избегая ложных срабатываний.
# Взято из публичных баз регулярных выражений для модерации в Telegram.
SWEAR_PATTERN = re.compile(
    r'(?iu)\b('
    r'(?:[оо́]|[пп́]р[ии́]|[зз́]а|[вв́]ы|[пп́]ере|[нн́]ед[оо́]|[нн́]а|[оо́]т|[сс́]|[пп́]од|[вв́]|[вв́]з|[вв́]оз|[ии́]з|[ии́]с|[дд́]о|[оо́]б|[бб́]ез|[бб́]ес|[пп́]р[ее́]д|[вв́]н[ее́]|[мме́]ж|[рр́]аз|[рр́]ас)?'
    r'(?:'
    r'х[уу́][йеёяию]|'
    r'п[ии́]зд|'
    r'[ее́ё]б[аеоуиы]|'
    r'[бб́]л[яя́][ддт]|'
    r'м[уу́]д[аео]|'
    r'п[ии́]д[оае]р|'
    r'шл[юю́]х|'
    r'[хх́]ер|'
    r'г[ао][нн́]д[оа]н|'
    r'з[аа́]л[уу́]п'
    r')\w*'
    r')\b'
)

def contains_swear_words(text: str) -> bool:
    """
    Проверяет текст на наличие нецензурной лексики.
    Возвращает True, если мат найден, иначе False.
    """
    if not text:
        return False
        
    # Предварительная очистка текста от некоторых спецсимволов для обхода фильтра
    cleaned_text = text.replace('@', 'а').replace('0', 'о').replace('1', 'и').replace('3', 'з').replace('*', '')
    
    # Исключения (ложные срабатывания)
    exceptions = ['хлеб', 'оскорблять', 'потреблять', 'ребенок', 'страховать', 'рубля', 'залупается']
    for exc in exceptions:
        if exc in cleaned_text.lower():
            # Если найдено слово-исключение, мы временно вырезаем его из текста перед проверкой регуляркой
            cleaned_text = cleaned_text.lower().replace(exc, '')
            
    return bool(SWEAR_PATTERN.search(cleaned_text))
