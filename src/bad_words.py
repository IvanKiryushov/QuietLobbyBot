import re

# Мощное регулярное выражение для поиска основных корней русского мата и грубых слов.
# Покрывает большинство словоформ, приставок и суффиксов, избегая ложных срабатываний.
SWEAR_PATTERN = re.compile(
    r'(?iu)\b('
    r'(?:[оо́]|[пп́]р[ии́]|[зз́]а|[вв́]ы|[пп́]ере|[нн́]ед[оо́]|[нн́]а|[оо́]т|[сс́]|[пп́]од|[вв́]|[вв́]з|[вв́]оз|[ии́]з|[ии́]с|[дд́]о|[оо́]б|[бб́]ез|[бб́]ес|[пп́]р[ее́]д|[вв́]н[ее́]|[мме́]ж|[рр́]аз|[рр́]ас)?'
    r'(?:'
    r'х[уу́\*][йеёяию]|'                 # хуй, х*й
    r'п[ии́\*]зд|'                       # пизда, п*зда
    r'[ее́ё\*]б(?:[аеоуиыёя\*]|н|л|р|с)|' # ебать, еб*ть, ебн, ебл, ебс
    r'[бб́]л[яя́\*](?:[ддт]\w*)?|'        # бля, блядь, бл*дь
    r'м[уу́\*]д[аео]|'                   # мудак, м*дак
    r'п[ии́\*]д[оае]?р|'                 # пидор, пидар, пидр, п*дор
    r'шл[юю́\*]х|'                       # шлюха, шл*ха
    r'[хх́]ер|'                          # хер
    r'г[ао\*][нн́]д[оа\*]н|'             # гандон, г*ндон
    r'з[аа́\*]л[уу́\*]п|'                 # залупа, з*лупа
    r'с[уу́\*]к[аиоеуя́\*]|с[уу́\*]чк|'    # сука, с*ка, сучка
    r'ур[оо́\*]д|'                       # урод, ур*д
    r'убл[юю́уу́\*]д'                       # ублюдок, убл*док
    r')\w*'
    r')\b'
)

def clean_text_variants(text: str) -> list[str]:
    """
    Генерирует несколько нормализованных вариантов текста:
    1. С заменой визуальных омоглифов (для русских слов с латинскими вставками).
    2. С полной фонетической транслитерацией латиницы в кириллицу.
    """
    if not text:
        return []

    # Приводим к нижнему регистру
    text_lower = text.lower()

    # Очищаем от некоторых спецсимволов-разделителей (но оставляем звездочку)
    # Удаляем точки, подчеркивания, дефисы, если они внутри слов
    cleaned = re.sub(r'[\._\-\+]', '', text_lower)

    # 1. Вариант с заменой визуальных омоглифов (цифры на буквы, латинские похожие на русские)
    visual_map = str.maketrans({
        'a': 'а', 'A': 'а',
        'b': 'б', 'B': 'в',
        'c': 'с', 'C': 'с',
        'e': 'е', 'E': 'е',
        'k': 'к', 'K': 'к',
        'o': 'о', 'O': 'о',
        'p': 'р', 'P': 'р',
        't': 'т', 'T': 'т',
        'x': 'х', 'X': 'х',
        'y': 'у', 'Y': 'у',
        '0': 'о',
        '3': 'з',
        '1': 'и',
        '@': 'а',
        '$': 'с'
    })
    variant_visual = cleaned.translate(visual_map)

    # 2. Вариант с фонетическим транслитом (когда слово написано латиницей целиком)
    # Сначала заменяем сложные буквосочетания
    translit_pre = cleaned
    replacements = {
        'ya': 'я', 'ia': 'я',
        'yu': 'ю', 'iu': 'ю',
        'yo': 'ё', 'jo': 'ё',
        'zh': 'ж',
        'ch': 'ч',
        'sh': 'ш',
        'ts': 'ц',
        'tc': 'ц',
    }
    for eng, rus in replacements.items():
        translit_pre = translit_pre.replace(eng, rus)

    # Затем посимвольный маппинг транслита
    translit_map = str.maketrans({
        'a': 'а',
        'b': 'б',
        'c': 'с',
        'd': 'д',
        'e': 'е',
        'f': 'ф',
        'g': 'г',
        'h': 'х',
        'i': 'и',
        'j': 'й',
        'k': 'к',
        'l': 'л',
        'm': 'м',
        'n': 'н',
        'o': 'о',
        'p': 'п',
        'r': 'р',
        's': 'с',
        't': 'т',
        'u': 'у',
        'v': 'в',
        'w': 'в',
        'x': 'х',
        'y': 'й',
        'z': 'з',
    })
    variant_translit = translit_pre.translate(translit_map)

    # Возвращаем список уникальных вариантов для проверки
    return list(set([cleaned, variant_visual, variant_translit]))

def contains_swear_words(text: str) -> bool:
    """
    Проверяет текст на наличие нецензурной лексики.
    Возвращает True, если мат найден, иначе False.
    """
    if not text:
        return False

    variants = clean_text_variants(text)
    
    # Исключения (нейтральные слова, которые могут содержать матерные корни)
    exceptions = [
        'хлеб', 'оскорблять', 'потреблять', 'ребенок', 'страховать', 'рубля', 'залупается',
        'уродился', 'уродилась', 'уродились', 'уродиться', 'уродится', 'уродит', 'уродятся',
        'себя', 'себе'
    ]

    for variant in variants:
        # Проверяем исключения в каждом варианте
        temp_variant = variant
        for exc in exceptions:
            if exc in temp_variant:
                temp_variant = temp_variant.replace(exc, '')
        
        if bool(SWEAR_PATTERN.search(temp_variant)):
            return True

    return False

